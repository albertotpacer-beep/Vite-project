create table if not exists public.event_favourites (
  user_id uuid not null references auth.users(id) on delete cascade,
  event_id bigint not null references public.events(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, event_id)
);

alter table public.event_favourites enable row level security;
grant select, insert, delete on public.event_favourites to authenticated;

drop policy if exists "Users can read their own favourites" on public.event_favourites;
create policy "Users can read their own favourites"
on public.event_favourites
for select
to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "Users can add their own favourites" on public.event_favourites;
create policy "Users can add their own favourites"
on public.event_favourites
for insert
to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists "Users can remove their own favourites" on public.event_favourites;
create policy "Users can remove their own favourites"
on public.event_favourites
for delete
to authenticated
using ((select auth.uid()) = user_id);
